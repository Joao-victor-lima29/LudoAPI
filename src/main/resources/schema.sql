CREATE TABLE IF NOT EXISTS jogos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR(120) NOT NULL,
    categoria VARCHAR(80) NOT NULL,
    minimo_jogadores INTEGER NOT NULL CHECK (minimo_jogadores >= 1),
    maximo_jogadores INTEGER NOT NULL CHECK (maximo_jogadores >= minimo_jogadores),
    duracao_minutos INTEGER NOT NULL CHECK (duracao_minutos >= 1)
);
